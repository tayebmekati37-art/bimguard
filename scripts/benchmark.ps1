<#
 Measures validation runtime on the demo project.

 Loads a fresh copy of the demo, uploads A-101 v13, then runs validation N
 times and reports p50 / p95 / min / max / mean runtime. Also confirms that
 every run produces the same findings (determinism check).

 What this measures: wall time of POST /projects/{id}/validate on this machine
 with this dataset.
 What this does NOT measure: precision or recall of the rules. That would
 require labeled ground truth that does not exist in this dataset.
#>
param(
    [string]$ApiUrl = "http://localhost:8000",
    [int]$Runs = 5
)
$ErrorActionPreference = "Stop"

try {
    Invoke-WebRequest "$ApiUrl/health" -UseBasicParsing -TimeoutSec 3 | Out-Null
} catch {
    Write-Host "[FAIL] API is not running at $ApiUrl." -ForegroundColor Red
    Write-Host "Start it first: powershell -ExecutionPolicy Bypass -File scripts\start.ps1"
    exit 1
}

$root   = Split-Path -Parent $PSScriptRoot
$ifcDir = Join-Path $root "data\sample_ifc"
$jsonDir = Join-Path $root "data\sample_projects\factory_expansion"

function Call($Method, $Path, $Token, $Body, $Form) {
    $params = @{ Uri = "$ApiUrl$Path"; Method = $Method; UseBasicParsing = $true; Headers = @{} }
    if ($Token) { $params.Headers["Authorization"] = "Bearer $Token" }
    if ($Form) { $params.Body = $Form } elseif ($Body) {
        $params.Body = ($Body | ConvertTo-Json -Depth 10); $params.ContentType = "application/json"
    }
    try { (Invoke-WebRequest @params).Content | ConvertFrom-Json }
    catch { throw "API call $Method $Path failed: $($_.ErrorDetails.Message)" }
}

function Upload($DocId, $Token, $File, $Revision, $Summary, $Status = "approved") {
    $out = Join-Path $env:TEMP "bimguard_bench_upload.json"
    $code = & curl.exe -s -o $out -w "%{http_code}" -X POST -H "Authorization: Bearer $Token" `
        -F "file=@$File" -F "revision_number=$Revision" -F "status=$Status" -F "change_summary=$Summary" `
        "$ApiUrl/documents/$DocId/revisions"
    if ($code -ne "201") { throw "Upload of $File failed ($code)" }
}

function Wait-Extraction($DocId, $Token) {
    for ($i = 0; $i -lt 30; $i++) {
        $revs = Call "GET" "/documents/$DocId/revisions" $Token
        if (($revs | Select-Object -First 1).extraction_status -ne "pending") { return }
        Start-Sleep -Seconds 1
    }
    throw "extraction timeout for $DocId"
}

function Percentile($arr, $p) {
    if ($arr.Count -eq 0) { return 0 }
    $sorted = $arr | Sort-Object
    $idx = [Math]::Ceiling(($p / 100.0) * $sorted.Count) - 1
    if ($idx -lt 0) { $idx = 0 }
    if ($idx -ge $sorted.Count) { $idx = $sorted.Count - 1 }
    return $sorted[$idx]
}

Write-Host "=== Benchmark: validation runtime on demo project ($Runs runs) ===" -ForegroundColor Cyan
Write-Host ""

$token = (Call "POST" "/auth/login" $null $null @{
    username = "admin@example.local"; password = "admin-demo-pass"
}).access_token

$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$project = Call "POST" "/projects" $token @{
    name = "Benchmark $stamp"; client = "Benchmark"; description = "Auto-generated by benchmark.ps1"
}
$pid = $project.id
Write-Host "Project: $($project.name) ($pid)"

$docs = @(
    @{ n = "A-101"; d = "architecture"; f = Join-Path $ifcDir "architecture_v1.ifc"; r = 12 },
    @{ n = "S-201"; d = "structure";    f = Join-Path $ifcDir "structure_v1.ifc";    r = 8  },
    @{ n = "M-301"; d = "mep";          f = Join-Path $ifcDir "mep_v1.ifc";          r = 5  },
    @{ n = "Q-101"; d = "quantity";     f = Join-Path $jsonDir "quantity_v1.json";   r = 6  },
    @{ n = "E-020"; d = "equipment";    f = Join-Path $jsonDir "equipment_v1.json";  r = 3  }
)
$ids = @{}
foreach ($doc in $docs) {
    $created = Call "POST" "/projects/$pid/documents" $token @{ document_number = $doc.n; name = $doc.n; discipline = $doc.d }
    $ids[$doc.n] = $created.id
    Upload $created.id $token $doc.f $doc.r "Baseline"
    Wait-Extraction $created.id $token
}

$links = @(
    @{ s = "S-201"; t = "A-101"; k = "depends_on";        c = 0.95; r = "r1" },
    @{ s = "M-301"; t = "A-101"; k = "depends_on";        c = 0.90; r = "r2" },
    @{ s = "Q-101"; t = "A-101"; k = "quantity_based_on"; c = 1.00; r = "r3" },
    @{ s = "E-020"; t = "M-301"; k = "depends_on";        c = 0.80; r = "r4" },
    @{ s = "M-301"; t = "S-201"; k = "spatially_related_to"; c = 0.60; r = "r5" }
)
foreach ($l in $links) {
    Call "POST" "/dependencies" $token @{
        source_document_id = $ids[$l.s]; target_document_id = $ids[$l.t]
        relationship_type  = $l.k; confidence = $l.c; reason = $l.r
    } | Out-Null
}

Upload $ids["A-101"] $token (Join-Path $ifcDir "architecture_v2.ifc") 13 `
    "Wall W-204 moved, door D-202A relocated, room 204 changed, wall W-207 added" "in_review"
Wait-Extraction $ids["A-101"] $token
Write-Host "Demo project ready. Starting $Runs validation runs..."
Write-Host ""

$times = @()
$signatures = @()

for ($i = 1; $i -le $Runs; $i++) {
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $run = Call "POST" "/projects/$pid/validate" $token
    $sw.Stop()
    $ms = [int]$sw.ElapsedMilliseconds
    $times += $ms

    # Signature = deterministic summary (status + per-rule counts)
    $sig = "{0}|{1}" -f $run.status, (($run.summary.by_rule.PSObject.Properties | Sort-Object Name | ForEach-Object { "$($_.Name)=$($_.Value)" }) -join ",")
    $signatures += $sig

    Write-Host ("  run {0}: {1} ms  (status={2}, total={3})" -f $i, $ms, $run.status, $run.summary.total)
}

Write-Host ""

# --- stats ---
$stats = [PSCustomObject]@{
    runs         = $Runs
    min_ms       = ($times | Measure-Object -Minimum).Minimum
    max_ms       = ($times | Measure-Object -Maximum).Maximum
    mean_ms      = [Math]::Round(($times | Measure-Object -Average).Average, 1)
    p50_ms       = Percentile $times 50
    p95_ms       = Percentile $times 95
}

Write-Host "=== Runtime ===" -ForegroundColor Cyan
Write-Host ("  min  = {0} ms" -f $stats.min_ms)
Write-Host ("  p50  = {0} ms" -f $stats.p50_ms)
Write-Host ("  mean = {0} ms" -f $stats.mean_ms)
Write-Host ("  p95  = {0} ms" -f $stats.p95_ms)
Write-Host ("  max  = {0} ms" -f $stats.max_ms)
Write-Host ""

# --- determinism check ---
Write-Host "=== Determinism ===" -ForegroundColor Cyan
$uniqueSigs = $signatures | Sort-Object -Unique
if ($uniqueSigs.Count -eq 1) {
    Write-Host ("  [ ok ] all {0} runs produced the same findings" -f $Runs) -ForegroundColor Green
    $passed = $true
} else {
    Write-Host ("  [FAIL] {0} distinct signatures across {1} runs:" -f $uniqueSigs.Count, $Runs) -ForegroundColor Red
    $uniqueSigs | ForEach-Object { Write-Host ("    {0}" -f $_) }
    $passed = $false
}
Write-Host ""

# --- cleanup ---
try { Call "DELETE" "/projects/$pid" $token | Out-Null; Write-Host "Deleted benchmark project $pid" } catch { Write-Host "[WARN] cleanup failed" }

Write-Host ""
if ($passed) {
    Write-Host "PASS" -ForegroundColor Green
    exit 0
} else {
    Write-Host "FAIL" -ForegroundColor Red
    exit 1
}