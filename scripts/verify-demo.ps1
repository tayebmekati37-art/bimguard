<#
 Verifies the demo end-to-end against a running API.

 Loads a fresh copy of the sample project, uploads A-101 v13, and asserts
 the specific states that the demo document (docs/evaluation/demo-dataset.md)
 promises. Any mismatch exits non-zero so this can be used as a gate.

 Run: powershell -ExecutionPolicy Bypass -File C:\dev\bimguard\scripts\verify-demo.ps1
 Optional: -ApiUrl, -SkipIfApiDown
#>
param(
    [string]$ApiUrl = "http://localhost:8000",
    [switch]$SkipIfApiDown
)
$ErrorActionPreference = "Stop"

# --- is the API up? ---
try {
    Invoke-WebRequest "$ApiUrl/health" -UseBasicParsing -TimeoutSec 3 | Out-Null
} catch {
    if ($SkipIfApiDown) {
        Write-Host "[SKIP] API is not running at $ApiUrl. Demo verification skipped." -ForegroundColor Yellow
        exit 0
    }
    Write-Host "[FAIL] API is not running at $ApiUrl." -ForegroundColor Red
    Write-Host "Start it first: powershell -ExecutionPolicy Bypass -File scripts\start.ps1"
    exit 1
}

$root   = Split-Path -Parent $PSScriptRoot
$ifcDir = Join-Path $root "data\sample_ifc"
$jsonDir = Join-Path $root "data\sample_projects\factory_expansion"

$script:failures = 0
$script:checks   = 0

function Assert-Equal($Actual, $Expected, $Label) {
    $script:checks++
    if ($Actual -ne $Expected) {
        $script:failures++
        Write-Host ("[FAIL] {0}: expected '{1}', got '{2}'" -f $Label, $Expected, $Actual) -ForegroundColor Red
    } else {
        Write-Host ("[ ok ] {0}: {1}" -f $Label, $Actual) -ForegroundColor Green
    }
}

function Assert-In($Actual, $Allowed, $Label) {
    $script:checks++
    if ($Actual -notin $Allowed) {
        $script:failures++
        Write-Host ("[FAIL] {0}: got '{1}', expected one of {2}" -f $Label, $Actual, ($Allowed -join "|")) -ForegroundColor Red
    } else {
        Write-Host ("[ ok ] {0}: {1}" -f $Label, $Actual) -ForegroundColor Green
    }
}

function Assert-Greater($Actual, $Threshold, $Label) {
    $script:checks++
    if ($Actual -le $Threshold) {
        $script:failures++
        Write-Host ("[FAIL] {0}: {1} is not greater than {2}" -f $Label, $Actual, $Threshold) -ForegroundColor Red
    } else {
        Write-Host ("[ ok ] {0}: {1} > {2}" -f $Label, $Actual, $Threshold) -ForegroundColor Green
    }
}

function Call($Method, $Path, $Token, $Body, $Form) {
    $params = @{ Uri = "$ApiUrl$Path"; Method = $Method; UseBasicParsing = $true; Headers = @{} }
    if ($Token) { $params.Headers["Authorization"] = "Bearer $Token" }
    if ($Form) { $params.Body = $Form } elseif ($Body) {
        $params.Body = ($Body | ConvertTo-Json -Depth 10); $params.ContentType = "application/json"
    }
    try { (Invoke-WebRequest @params).Content | ConvertFrom-Json }
    catch { throw "API call $Method $Path failed: $($_.ErrorDetails.Message)" }
}

function Upload($DocId, $Token, $File, $Revision, $Summary, $Status = "approved") {
    $out = Join-Path $env:TEMP "bimguard_verify_upload.json"
    $code = & curl.exe -s -o $out -w "%{http_code}" -X POST -H "Authorization: Bearer $Token" `
        -F "file=@$File" -F "revision_number=$Revision" -F "status=$Status" -F "change_summary=$Summary" `
        "$ApiUrl/documents/$DocId/revisions"
    if ($code -ne "201") { throw "Upload of $File failed ($code): $(Get-Content $out -Raw)" }
}

function Wait-Extraction($DocId, $Token, $TimeoutSeconds = 30) {
    for ($i = 0; $i -lt $TimeoutSeconds; $i++) {
        $revs = Call "GET" "/documents/$DocId/revisions" $Token
        $latest = $revs | Select-Object -First 1
        if ($latest.extraction_status -ne "pending") { return $latest }
        Start-Sleep -Seconds 1
    }
    throw "Extraction did not complete within ${TimeoutSeconds}s for document $DocId"
}

Write-Host "=== Verifying BIMGuard demo against $ApiUrl ===" -ForegroundColor Cyan
Write-Host ""

# --- login ---
$token = (Call "POST" "/auth/login" $null $null @{
    username = "admin@example.local"; password = "admin-demo-pass"
}).access_token
Write-Host "Logged in as admin@example.local"
Write-Host ""

# --- create project (unique name so re-runs don't collide) ---
$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$project = Call "POST" "/projects" $token @{
    name        = "Verify Demo $stamp"
    client      = "Verification"
    description = "Auto-generated by verify-demo.ps1"
}
Write-Host "Created project: $($project.name)"
$pid = $project.id

# --- create documents ---
$docs = @(
    @{ n = "A-101"; name = "Level 2 Floor Plan";        d = "architecture"; f = Join-Path $ifcDir "architecture_v1.ifc"; r = 12 },
    @{ n = "S-201"; name = "Level 2 Framing Plan";      d = "structure";    f = Join-Path $ifcDir "structure_v1.ifc";    r = 8  },
    @{ n = "M-301"; name = "Level 2 HVAC Layout";       d = "mep";          f = Join-Path $ifcDir "mep_v1.ifc";          r = 5  },
    @{ n = "Q-101"; name = "Level 2 Quantity Take-off"; d = "quantity";     f = Join-Path $jsonDir "quantity_v1.json";   r = 6  },
    @{ n = "E-020"; name = "Equipment Schedule";        d = "equipment";    f = Join-Path $jsonDir "equipment_v1.json";  r = 3  }
)
$ids = @{}
foreach ($doc in $docs) {
    $created = Call "POST" "/projects/$pid/documents" $token @{ document_number = $doc.n; name = $doc.name; discipline = $doc.d }
    $ids[$doc.n] = $created.id
    Upload $created.id $token $doc.f $doc.r "Baseline revision"
    Wait-Extraction $created.id $token | Out-Null
    Write-Host "  Uploaded $($doc.n) v$($doc.r)"
}

# --- dependencies ---
$links = @(
    @{ s = "S-201"; t = "A-101"; k = "depends_on";           c = 0.95; r = "Structural layout follows architecture" },
    @{ s = "M-301"; t = "A-101"; k = "depends_on";           c = 0.90; r = "HVAC routing follows architecture" },
    @{ s = "Q-101"; t = "A-101"; k = "quantity_based_on";    c = 1.00; r = "Take-offs measured from architecture" },
    @{ s = "E-020"; t = "M-301"; k = "depends_on";           c = 0.80; r = "Equipment coordinated with HVAC" },
    @{ s = "M-301"; t = "S-201"; k = "spatially_related_to"; c = 0.60; r = "Ducts must clear framing" }
)
foreach ($l in $links) {
    Call "POST" "/dependencies" $token @{
        source_document_id = $ids[$l.s]; target_document_id = $ids[$l.t]
        relationship_type  = $l.k; confidence = $l.c; reason = $l.r
    } | Out-Null
}
Write-Host "  Registered $($links.Count) dependencies"
Write-Host ""

# --- upload A-101 v13 ---
Upload $ids["A-101"] $token (Join-Path $ifcDir "architecture_v2.ifc") 13 `
    "Wall W-204 moved 300 mm, door D-202A relocated, room 204 parameters changed, wall W-207 added" "in_review"
Wait-Extraction $ids["A-101"] $token | Out-Null
Write-Host "Uploaded A-101 v13 (in_review)"
Write-Host ""

# --- verify health states ---
Write-Host "=== Health states ===" -ForegroundColor Cyan
$health = Call "GET" "/projects/$pid/health" $token

$byDoc = @{}
foreach ($d in $health.documents_health) { $byDoc[$d.document_number] = $d.state }

Assert-Equal $byDoc["A-101"] "warning" "A-101 health (v13 in_review, so not stale yet)"
Assert-Equal $byDoc["S-201"] "critical" "S-201 health"
Assert-Equal $byDoc["M-301"] "critical" "M-301 health"
Assert-Equal $byDoc["Q-101"] "critical" "Q-101 health"
Assert-Equal $byDoc["E-020"] "warning"  "E-020 health (indirect via M-301)"
Write-Host ""

# --- verify dependency staleness ---
Write-Host "=== Dependency staleness ===" -ForegroundColor Cyan
$graph = Call "GET" "/projects/$pid/graph" $token
$staleEdges = @($graph.edges | Where-Object { $_.is_stale })
Assert-Equal $staleEdges.Count 3 "stale dependency count"

$staleBySource = @{}
foreach ($e in $staleEdges) { $staleBySource[$e.source_number] = $true }
Assert-Equal $staleBySource.ContainsKey("S-201") $true "S-201 is stale against A-101"
Assert-Equal $staleBySource.ContainsKey("M-301") $true "M-301 is stale against A-101"
Assert-Equal $staleBySource.ContainsKey("Q-101") $true "Q-101 is stale against A-101"
Write-Host ""

# --- verify validation ---
Write-Host "=== Validation ===" -ForegroundColor Cyan
$run = Call "POST" "/projects/$pid/validate" $token
Assert-Equal $run.status "BLOCKED" "readiness status after A-101 v13"
Assert-Greater $run.summary.total 0 "total issue count"
Assert-Greater $run.summary.blocking 0 "blocking issue count"

$staleFindings = ($run.summary.by_rule.PSObject.Properties | Where-Object { $_.Name -eq "STALE_DEPENDENCY" }).Value
Assert-Equal $staleFindings 3 "STALE_DEPENDENCY finding count"

Write-Host ""
Write-Host "  Run summary (informational, not asserted):" -ForegroundColor Gray
Write-Host ("    documents_checked = {0}" -f $run.summary.documents_checked)
Write-Host ("    total issues     = {0}" -f $run.summary.total)
Write-Host ("    blocking issues  = {0}" -f $run.summary.blocking)
Write-Host ("    duration_ms      = {0}" -f $run.duration_ms)
Write-Host "    by rule:"
$run.summary.by_rule.PSObject.Properties | Sort-Object Name | ForEach-Object {
    Write-Host ("      {0,-32} {1}" -f $_.Name, $_.Value)
}
Write-Host ""

# --- cleanup: delete the project so re-runs stay clean ---
Write-Host "=== Cleanup ===" -ForegroundColor Cyan
try {
    Call "DELETE" "/projects/$pid" $token | Out-Null
    Write-Host "Deleted verification project $pid"
} catch {
    Write-Host "[WARN] Could not delete project ${pid}: $_" -ForegroundColor Yellow
}
Write-Host ""

# --- result ---
Write-Host "=== Result ===" -ForegroundColor Cyan
if ($script:failures -eq 0) {
    Write-Host ("PASS - {0}/{0} checks succeeded" -f $script:checks) -ForegroundColor Green
    exit 0
} else {
    Write-Host ("FAIL - {0} of {1} checks failed" -f $script:failures, $script:checks) -ForegroundColor Red
    exit 1
}